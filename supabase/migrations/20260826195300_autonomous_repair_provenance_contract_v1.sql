-- CONTENTFLOW_CHANGE_PROVENANCE_V1
-- change-class: control_plane_guardrail
-- purpose: Require Git provenance for persistent/structural autonomous repairs without blocking runtime-only repair actions.

create table if not exists public.contentflow_persistent_change_provenance (
  id bigint generated by default as identity primary key,
  change_id uuid not null default gen_random_uuid() unique,
  project_key text not null default 'contentflow',
  change_class text not null check (change_class in ('schema','function','policy','trigger','extension','persistent_control','other')),
  incident_id bigint,
  repair_recipe text,
  migration_name text,
  git_commit_sha text,
  git_pr_number bigint,
  causal_state_version text,
  evidence_id text,
  evidence jsonb not null default '{}'::jsonb,
  break_glass boolean not null default false,
  status text not null default 'intent_registered' check (status in ('intent_registered','admitted','applied','verified','quarantined','rejected')),
  requested_at timestamptz not null default now(),
  admitted_at timestamptz,
  applied_at timestamptz,
  verified_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint contentflow_persistent_change_git_sha_chk check (git_commit_sha is null or git_commit_sha ~ '^[0-9a-f]{40}$')
);

create index if not exists contentflow_persistent_change_provenance_status_idx
  on public.contentflow_persistent_change_provenance(status, requested_at);
create index if not exists contentflow_persistent_change_provenance_incident_idx
  on public.contentflow_persistent_change_provenance(project_key, incident_id, requested_at desc);

alter table public.contentflow_persistent_change_provenance enable row level security;
revoke all on table public.contentflow_persistent_change_provenance from public, anon, authenticated;
grant select, insert, update on table public.contentflow_persistent_change_provenance to service_role;

create or replace function public.contentflow_register_persistent_change_intent_v1(
  p_project_key text,
  p_change_class text,
  p_incident_id bigint default null,
  p_repair_recipe text default null,
  p_migration_name text default null,
  p_git_commit_sha text default null,
  p_git_pr_number bigint default null,
  p_causal_state_version text default null,
  p_evidence_id text default null,
  p_evidence jsonb default '{}'::jsonb,
  p_break_glass boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path='public','pg_temp'
as $function$
declare
  v_id uuid;
  v_status text;
begin
  if p_change_class not in ('schema','function','policy','trigger','extension','persistent_control','other') then
    raise exception 'unsupported_persistent_change_class:%', p_change_class;
  end if;

  if p_git_commit_sha is not null and p_git_commit_sha !~ '^[0-9a-f]{40}$' then
    raise exception 'invalid_git_commit_sha';
  end if;

  v_status := case when p_break_glass then 'quarantined' else 'intent_registered' end;

  insert into public.contentflow_persistent_change_provenance(
    project_key, change_class, incident_id, repair_recipe, migration_name,
    git_commit_sha, git_pr_number, causal_state_version, evidence_id, evidence,
    break_glass, status
  ) values (
    coalesce(nullif(p_project_key,''),'contentflow'), p_change_class, p_incident_id, p_repair_recipe,
    nullif(p_migration_name,''), nullif(lower(p_git_commit_sha),''), p_git_pr_number,
    nullif(p_causal_state_version,''), nullif(p_evidence_id,''), coalesce(p_evidence,'{}'::jsonb),
    coalesce(p_break_glass,false), v_status
  ) returning change_id into v_id;

  return jsonb_build_object(
    'architecture','AUTONOMOUS_REPAIR_PROVENANCE_CONTRACT_V1',
    'change_id',v_id,
    'status',v_status,
    'break_glass',coalesce(p_break_glass,false)
  );
end
$function$;

create or replace function public.contentflow_admit_persistent_change_v1(
  p_change_id uuid,
  p_git_commit_sha text,
  p_migration_name text,
  p_git_pr_number bigint default null,
  p_evidence_id text default null
)
returns jsonb
language plpgsql
security definer
set search_path='public','pg_temp'
as $function$
declare
  v_row public.contentflow_persistent_change_provenance%rowtype;
begin
  select * into v_row
  from public.contentflow_persistent_change_provenance
  where change_id=p_change_id
  for update;

  if not found then raise exception 'persistent_change_not_found'; end if;
  if v_row.break_glass then raise exception 'break_glass_change_requires_quarantine_reconciliation'; end if;
  if v_row.status not in ('intent_registered','rejected') then raise exception 'persistent_change_not_admittable:%',v_row.status; end if;
  if coalesce(p_git_commit_sha,'') !~ '^[0-9a-f]{40}$' then raise exception 'valid_git_commit_sha_required'; end if;
  if coalesce(nullif(p_migration_name,''),'')='' then raise exception 'migration_name_required'; end if;

  update public.contentflow_persistent_change_provenance
  set git_commit_sha=lower(p_git_commit_sha),
      migration_name=p_migration_name,
      git_pr_number=coalesce(p_git_pr_number,git_pr_number),
      evidence_id=coalesce(nullif(p_evidence_id,''),evidence_id),
      status='admitted',
      admitted_at=now(),
      updated_at=now()
  where change_id=p_change_id;

  return jsonb_build_object('admitted',true,'change_id',p_change_id,'migration_name',p_migration_name,'git_commit_sha',lower(p_git_commit_sha));
end
$function$;

create or replace function public.contentflow_assert_persistent_change_admission_v1(p_change_id uuid)
returns jsonb
language plpgsql
security definer
stable
set search_path='public','pg_temp'
as $function$
declare
  v_row public.contentflow_persistent_change_provenance%rowtype;
begin
  select * into v_row from public.contentflow_persistent_change_provenance where change_id=p_change_id;
  if not found then raise exception 'PERSISTENT_CHANGE_ADMISSION_DENIED:missing_change'; end if;
  if v_row.break_glass or v_row.status <> 'admitted' or v_row.git_commit_sha is null or v_row.migration_name is null then
    raise exception 'PERSISTENT_CHANGE_ADMISSION_DENIED:%',jsonb_build_object(
      'change_id',p_change_id,
      'status',v_row.status,
      'break_glass',v_row.break_glass,
      'has_git_sha',v_row.git_commit_sha is not null,
      'has_migration',v_row.migration_name is not null
    );
  end if;
  return jsonb_build_object('admitted',true,'change_id',p_change_id,'git_commit_sha',v_row.git_commit_sha,'migration_name',v_row.migration_name);
end
$function$;

create or replace function public.contentflow_mark_persistent_change_applied_v1(
  p_change_id uuid,
  p_evidence jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path='public','pg_temp'
as $function$
begin
  perform public.contentflow_assert_persistent_change_admission_v1(p_change_id);
  update public.contentflow_persistent_change_provenance
  set status='applied', evidence=coalesce(evidence,'{}'::jsonb)||coalesce(p_evidence,'{}'::jsonb), applied_at=now(), updated_at=now()
  where change_id=p_change_id;
  return jsonb_build_object('applied',true,'change_id',p_change_id);
end
$function$;

create or replace function public.contentflow_verify_persistent_change_v1(
  p_change_id uuid,
  p_evidence_id text,
  p_evidence jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path='public','pg_temp'
as $function$
declare v_status text;
begin
  select status into v_status from public.contentflow_persistent_change_provenance where change_id=p_change_id for update;
  if not found then raise exception 'persistent_change_not_found'; end if;
  if v_status <> 'applied' then raise exception 'persistent_change_not_verifiable:%',v_status; end if;
  if coalesce(nullif(p_evidence_id,''),'')='' then raise exception 'verification_evidence_required'; end if;

  update public.contentflow_persistent_change_provenance
  set status='verified', evidence_id=p_evidence_id,
      evidence=coalesce(evidence,'{}'::jsonb)||coalesce(p_evidence,'{}'::jsonb),
      verified_at=now(), updated_at=now()
  where change_id=p_change_id;

  return jsonb_build_object('verified',true,'change_id',p_change_id,'evidence_id',p_evidence_id);
end
$function$;

create or replace function public.contentflow_persistent_change_admission_status_v1()
returns jsonb
language sql
security definer
stable
set search_path='public','pg_temp'
as $function$
  select jsonb_build_object(
    'architecture','AUTONOMOUS_REPAIR_PROVENANCE_CONTRACT_V1',
    'fail_closed',true,
    'open_intents',count(*) filter (where status='intent_registered'),
    'admitted',count(*) filter (where status='admitted'),
    'applied_unverified',count(*) filter (where status='applied'),
    'quarantined',count(*) filter (where status='quarantined'),
    'verified',count(*) filter (where status='verified')
  )
  from public.contentflow_persistent_change_provenance;
$function$;

